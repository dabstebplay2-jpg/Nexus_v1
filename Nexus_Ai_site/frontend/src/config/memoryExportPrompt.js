/**
 * Meta-prompt для копирования в ChatGPT / Claude / Grok и др. —
 * чтобы собрать память о пользователе для импорта в NexusAI.
 */
export function buildExportPromptForOtherAi({ currentDraft = '' } = {}) {
  const draft = (currentDraft || '').trim();
  const draftBlock = draft
    ? `\n\n---\nТекущий черновик памяти в NexusAI (можно дополнить и улучшить):\n\n${draft}\n---\n`
    : '';

  return `Ты помогаешь мне импортировать контекст из одного ИИ-помощника в другого. Твоя задача – проанализировать наши предыдущие чаты и обобщить информацию обо мне.

В ответе не должно быть местоимений первого лица (я, мой, мне, мое, меня) и второго лица (ты, твой, тебе, твое, тебя). Называй человека, информацию о котором ты изучил, "пользователь" или используй нейтральные обращения.

По возможности сохраняй слова пользователя без изменений, особенно в инструкциях и описаниях предпочтений.

Категории (указывай сведения в том же порядке):
1. Демографическая информация: предпочитаемые имена, профессия, образование и место жительства.
2. Интересы и предпочтения: не просто собственность или разовые покупки пользователя, а то, с чем он часто взаимодействует.
3. Отношения: подтвержденные и постоянные.
4. Мероприятия, проекты и планы по датам: список недавних важных дел.
5. Инструкции: правила, которые пользователь просил соблюдать, например что нужно и нельзя делать, а также исправления в поведении ассистента. Включи правила только из сохраненных записей, а не из чатов.

Формат.
Создай разделы для каждой указанной выше категории. Постарайся включить точные цитаты из запросов пользователя, которые подтверждают сведения. Для каждого пункта используй приведенный ниже формат.
* Пользователя зовут <имя>.
    * Доказательство: пользователь сказал "Зови меня <имя>". Дата: [ДД.ММ.ГГГГ].

Результат:
- Укажи в ответе ТОЛЬКО запрошенную информацию без слов-паразитов, вводного текста и подписей.
- Текст должен быть готов для вставки в поле «Память» в настройках NexusAI (до ~8000 символов).

В конце добавь "Импортировано из <название>", подставив вместо названия ChatGPT, Claude, Grok, NexusAI или другой ИИ, в котором ты сейчас работаешь. Это должно быть последнее предложение в тексте.${draftBlock}`;
}
